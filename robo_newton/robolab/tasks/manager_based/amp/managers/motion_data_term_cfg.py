from __future__ import annotations

from dataclasses import MISSING

from isaaclab.utils import configclass

@configclass 
class MotionDataTermCfg:
    """
    Configuration for the motion data term in the motion data manager.
    """
    
    weight: float = 1.0
    """Weight of this term in the motion data manager."""
    
    motion_data_dir: str = MISSING
    """Directory containing motion data files.
    
    Reads validated roboparty_motion_v1 .npz files (XYZW, named joints).
    """
    
    motion_data_weights: dict[str, float] = MISSING
    """Weights for the motion data in this term."""

    sampling_mode: str = "static"
    """Motion-id sampling mode: ``static`` or command-matched."""

    command_name: str | None = None
    """Command term used by command-matched motion sampling."""

    command_match_temperature: float = 0.5
    """Temperature for the soft command-to-motion matching distribution."""

    command_match_min_probability: float = 0.02
    """Minimum fraction of the configured prior retained by command matching."""

    command_match_velocity_scale: float = 0.5
    """Planar velocity scale (m/s) used to normalize matching error on vx and vy."""

    command_match_yaw_scale: float = 0.5
    """Yaw-rate scale (rad/s) used to normalize matching error."""

    command_match_direction_weight: float = 1.0
    """Weight for uncommanded-axis and opposite-direction motion penalties."""

    command_match_direction_threshold: float = 0.1
    """Minimum command/motion magnitude considered active for direction matching."""

    command_match_current_weight: float = 0.3
    """Weight of the robot's current body-frame velocity in the match target."""

    command_match_target_weight: float = 0.7
    """Weight of the commanded velocity in the match target."""

    command_match_static_threshold: float = 0.0
    """Commands below this magnitude use only the configured static motions."""

    command_match_static_motion_names: tuple[str, ...] = ()
    """Motion names reserved for commands below ``command_match_static_threshold``."""

    command_match_cruise_speed_threshold: float = 0.0
    """Planar-speed gate (m/s) for command-match clip features.

    Frames with ``hypot(vx, vy)`` at or above this value are averaged into the
    clip feature. ``0`` keeps the whole-clip mean, including standing frames.
    """

    command_match_cruise_min_fraction: float = 0.1
    """Minimum cruise-frame fraction required to use the gated mean.

    Below this fraction the matcher falls back to the whole-clip mean, so
    in-place turns are not described by a handful of stepping frames.
    """

    key_body_names: list[str] | None = None
    """Ordered key-body names or regular-expression patterns; missing bodies may be generated by startup FK."""

    resample_fps: float | None = 120.0
    """Resample every loaded clip to this frame rate before anything else.

    Each clip's own ``sample_rate`` is read first; positions / joints are
    linearly interpolated and quaternions are slerped onto a uniform grid at
    ``resample_fps``. ``None`` keeps each clip at its native rate.
    """
